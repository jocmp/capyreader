    private fun defineWideCharacters() {
        val letterSurrogates = listOf(0xDC00, 0xDC34, 0xDC68, 0xDD04, 0xDD6C, 0xDDA0, 0xDDD4, 0xDE08, 0xDE70)
        val capitalSurrogates = listOf(0xDD38, 0xDC9C)
        val digitSurrogates = listOf(0xDFCE, 0xDFE2, 0xDFEC, 0xDFF6)

        LETTERS.forEachIndexed { i, c ->
            val ch = c.toString()
            letterSurrogates.forEach { low -> defineWide(ch, low + i) }

            if (i < 26) {
                capitalSurrogates.forEach { low -> defineWide(ch, low + i) }
            }
        }

        defineWide("k", 0xDD5C)

        (0 until 10).forEach { i ->
            val ch = i.toString()
            digitSurrogates.forEach { low -> defineWide(ch, low + i) }
        }
    }

    private fun defineWide(ch: String, lowSurrogate: Int) {
        val wideChar = charArrayOf(0xD835.toChar(), lowSurrogate.toChar()).concatToString()
        defineSymbol(Mode.MATH, main, mathord, ch, wideChar)
        defineSymbol(Mode.TEXT, main, textord, ch, wideChar)
    }

    private fun defineExtraLatin() {
        extraLatin.forEach { c ->
            val ch = c.toString()
            defineSymbol(Mode.MATH, main, mathord, ch, ch)
            defineSymbol(Mode.TEXT, main, textord, ch, ch)
        }
    }
