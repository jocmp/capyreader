    private fun defineSymbol(
        mode: Mode,
        font: String,
        group: String,
        replace: String?,
        name: String,
        acceptUnicodeChar: Boolean = false,
    ) {
        val table = if (mode == Mode.MATH) mathTable else textTable
        val info = SymbolInfo(font = font, group = group, replace = replace)
        table[name] = info

        if (acceptUnicodeChar && !replace.isNullOrEmpty()) {
            table[replace] = info
        }
    }

